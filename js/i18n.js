function applyLang(lang) {
  const dict = I18N[lang] || I18N.ja;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = dict[el.dataset.i18n];
    if (value == null) return;
    if (el.hasAttribute("data-i18n-html")) el.innerHTML = value;
    else if (el.tagName === "META") el.setAttribute("content", value);
    else if (el.tagName === "TITLE") el.textContent = value;
    else if (el.dataset.i18nAttr) el.setAttribute(el.dataset.i18nAttr, value);
    else el.textContent = value;
  });
  document.querySelectorAll("iframe[data-map]").forEach((frame) => {
    const src = frame.getAttribute("src") || "";
    frame.setAttribute("src", src.replace(/hl=(ja|en)/, `hl=${lang}`));
  });
  document.querySelectorAll("[data-set-lang]").forEach((btn) => {
    btn.classList.toggle("is-active", btn.dataset.setLang === lang);
    btn.setAttribute("aria-pressed", String(btn.dataset.setLang === lang));
  });
  localStorage.setItem("sens-lang", lang);
}

const initialLang = localStorage.getItem("sens-lang") === "en" ? "en" : "ja";
applyLang(initialLang);

document.querySelectorAll("[data-set-lang]").forEach((btn) => {
  btn.addEventListener("click", () => applyLang(btn.dataset.setLang));
});
